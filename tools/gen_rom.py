#!/usr/bin/env python3
"""Turn a hex word list (one 32-bit word per line) into rtl/boot_rom_data.vhd."""
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "build/boot_rom_init.txt"
dst = sys.argv[2] if len(sys.argv) > 2 else "rtl/boot_rom_data.vhd"
words = [l.strip() for l in open(src) if l.strip()]
if len(words) > 1024:
    sys.exit(f"boot ROM is {len(words)} words, only 1024 fit")
words += ["00000000"] * (1024 - len(words))
body = ",\n".join(f'        x"{w}"' for w in words)
open(dst, "w").write(f"""-- generated by tools/gen_rom.py from {src}; do not edit
library ieee;
use ieee.std_logic_1164.all;

package boot_rom_data is
    type rom_t is array (0 to 1023) of std_logic_vector(31 downto 0);
    constant ROM_INIT : rom_t := (
{body}
    );
end boot_rom_data;
""")
